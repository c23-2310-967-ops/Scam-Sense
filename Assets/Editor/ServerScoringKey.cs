using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Tools > Scam Sense > Export Server Scoring Key
/// The server recalculates every uploaded run (public.submit_game_result) with its own copy of each room's scoring
/// rules and answer key (scoring.level_rules / scoring.level_messages). This writes that copy from the Level assets as
/// a new Supabase migration, supabase/migrations/{timestamp}_scoring_key.sql, which is then applied to the database.
/// Run it after changing any level's messages, verdicts, scoring rules or star/unlock scores;
/// ServerScoringKeyTests fails until the latest exported key matches the assets again.
/// </summary>
public static class ServerScoringKey
{
    public const string CatalogPath = "Assets/Levels/LevelCatalog.asset";
    static string MigrationsDir => Path.Combine(Path.GetDirectoryName(Application.dataPath), "supabase", "migrations");

    [MenuItem("Tools/Scam Sense/Export Server Scoring Key")]
    static void ExportMenu() => Debug.Log(Export());

    /// <summary>Writes a new key migration if the assets changed since the last one. Returns a summary.</summary>
    public static string Export()
    {
        string sql = Generate(AssetDatabase.LoadAssetAtPath<LevelCatalog>(CatalogPath));
        string latest = LatestKeyFile();
        if (latest != null && Body(File.ReadAllText(latest)) == Body(sql))
            return $"Server scoring key is already up to date ({Path.GetFileName(latest)}).";
        string path = Path.Combine(MigrationsDir, DateTime.UtcNow.ToString("yyyyMMddHHmmss") + "_scoring_key.sql");
        File.WriteAllText(path, sql);
        return $"Wrote {path}. Apply it to the Supabase database (it replaces the server's answer key).";
    }

    /// <summary>The newest *_scoring_key.sql migration, or null.</summary>
    public static string LatestKeyFile() =>
        Directory.Exists(MigrationsDir)
            ? Directory.GetFiles(MigrationsDir, "*_scoring_key.sql").OrderBy(Path.GetFileName, StringComparer.Ordinal).LastOrDefault()
            : null;

    /// <summary>The SQL without comment lines (so only the key itself is compared).</summary>
    public static string Body(string sql) =>
        string.Join("\n", sql.Replace("\r\n", "\n").Split('\n').Where(l => !l.TrimStart().StartsWith("--")));

    /// <summary>Replaces the server's rules and answer key with the catalog's levels.</summary>
    public static string Generate(LevelCatalog catalog)
    {
        var levels = catalog.levels.Where(l => l != null).ToList();
        var sb = new StringBuilder();
        sb.Append("-- Server answer key and scoring rules used by public.submit_game_result.\n");
        sb.Append("-- GENERATED by Tools > Scam Sense > Export Server Scoring Key from Assets/Levels. Do not edit by hand.\n\n");
        sb.Append("delete from scoring.level_rules where level_id not in (")
          .Append(string.Join(", ", levels.Select(l => Str(l.levelId)))).Append(");\n\n");

        sb.Append("insert into scoring.level_rules (level_id, base_points, speed_bonus, fast_window, wrong_penalty, recovery_points,\n")
          .Append("  overtime_step_seconds, overtime_penalty_per_step, max_time_penalty, min_correct_points,\n")
          .Append("  one_star, two_star, three_star, unlock_score, message_count) values\n");
        sb.Append(string.Join(",\n", levels.Select(l =>
        {
            var c = l.scoring;
            return $"  ({Str(l.levelId)}, {c.basePoints}, {c.speedBonus}, {Num(c.fastWindow)}, {c.wrongPenalty}, {c.recoveryPoints}, " +
                   $"{Num(c.overtimeStepSeconds)}, {c.overtimePenaltyPerStep}, {c.maxTimePenalty}, {c.minCorrectPoints}, " +
                   $"{l.oneStarScore}, {l.twoStarScore}, {l.threeStarScore}, {l.minScoreToUnlockNext}, {l.MessageCount})";
        })));
        sb.Append("\non conflict (level_id) do update set base_points = excluded.base_points, speed_bonus = excluded.speed_bonus,\n")
          .Append("  fast_window = excluded.fast_window, wrong_penalty = excluded.wrong_penalty, recovery_points = excluded.recovery_points,\n")
          .Append("  overtime_step_seconds = excluded.overtime_step_seconds, overtime_penalty_per_step = excluded.overtime_penalty_per_step,\n")
          .Append("  max_time_penalty = excluded.max_time_penalty, min_correct_points = excluded.min_correct_points,\n")
          .Append("  one_star = excluded.one_star, two_star = excluded.two_star, three_star = excluded.three_star,\n")
          .Append("  unlock_score = excluded.unlock_score, message_count = excluded.message_count;\n\n");

        sb.Append("delete from scoring.level_messages;\n\n");
        sb.Append("insert into scoring.level_messages (level_id, message_id, is_scam, allowance_seconds) values\n");
        var go = new GameObject("ServerScoringKey") { hideFlags = HideFlags.HideAndDontSave };
        try
        {
            var scoring = go.AddComponent<ScoringSystem>();
            var rows = levels.SelectMany(l =>
            {
                scoring.Configure(l);   // the reading allowance depends on the level's rules
                return l.messages.Where(m => m != null).Select(m =>
                    $"  ({Str(l.levelId)}, {Str(m.id)}, {(m.correctVerdict == MessageVerdict.Scam ? "true" : "false")}, {Num(scoring.ReadingAllowance(m))})").ToList();
            });
            sb.Append(string.Join(",\n", rows)).Append(";\n");
        }
        finally { UnityEngine.Object.DestroyImmediate(go); }
        return sb.ToString();
    }

    static string Str(string s) => "'" + (s ?? "").Replace("'", "''") + "'";
    static string Num(float f) => f.ToString("R", CultureInfo.InvariantCulture);
}
